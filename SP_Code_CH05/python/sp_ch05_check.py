"""SP_CH05 — number checks for every example and exercise of Chapter 5."""
import numpy as np
from scipy.stats import norm
def show(l,v): print(f"{l:<60} {v}")
def joint_stats(J):
    x=np.arange(J.shape[0]); y=np.arange(J.shape[1]); pX=J.sum(1); pY=J.sum(0)
    EX=(x*pX).sum(); EY=(y*pY).sum(); EXY=sum(i*j*J[i,j] for i in x for j in y)
    VX=(x**2*pX).sum()-EX**2; VY=(y**2*pY).sum()-EY**2; cov=EXY-EX*EY
    return dict(pX=pX.round(3),pY=pY.round(3),EX=round(EX,3),EY=round(EY,3),EXY=round(EXY,3),cov=round(cov,4),VX=round(VX,4),VY=round(VY,4),rho=round(cov/np.sqrt(VX*VY),3),condYgivenX=[(J[i]/J[i].sum()).round(3) for i in x],EYgivenX=[round((y*J[i]/J[i].sum()).sum(),3) for i in x])
J=np.array([[0.45,0.10,0.02],[0.15,0.12,0.05],[0.03,0.05,0.03]])
show("Examples 5.1–5.7 (book joint table)",joint_stats(J))
